/** Typical wall-panel resolutions (approximate, not tied to one product), landscape. */
const WALL = [
  ['wall-800x480', '7″ panel 800 × 480', 800, 480],
  ['wall-1024x600', '7–10″ panel 1024 × 600', 1024, 600],
  ['wall-1280x800', '10″ panel 1280 × 800', 1280, 800],
  ['wall-1920x1080', 'Full HD 1920 × 1080', 1920, 1080],
]

export function devicePresets() {
  const list = FROM_PLAYWRIGHT.map(([id, name, group, frame, safe]) => {
    const d = devices[name]
    if (!d) throw new Error(`Playwright has no device "${name}"`)
    const size = d.screen || d.viewport
    return {
      id,
      label: name,
      group,
      w: size.width,
      h: size.height,
      sizeSource: d.screen ? 'playwright-screen' : 'playwright-viewport',
      frame,
      safe: SAFE[safe],
      safeApprox: true,
    }
  })
  for (const [id, label, w, h] of WALL) {
    list.push({ id, label, group: 'wall', w: h, h: w, landscape: true, sizeSource: 'typical', frame: 'wall', safe: SAFE.none, safeApprox: true })
  }
  return list
}

export function generateDevicePresets() {
  const body = JSON.stringify(devicePresets(), null, 2)
  const out = `// Generated by scripts/gen-device-presets.mjs from Playwright's device registry. Do not edit.
// Sizes: CSS px in portrait (w < h). sizeSource "playwright-screen" = the whole display,
// "playwright-viewport" = the browser viewport Playwright lists (no screen size given),
// "typical" = a typical wall-panel resolution (approximate; landscape: true = shown wide).
// Safe-area insets are APPROXIMATIONS per device class, not measurements.
export const DEVICE_PRESETS = ${body};

export const DEFAULT_DEVICE = "iphone-15-pro";
`
  return { [DEVICES_OUTPUT]: out }
}

if (resolve(process.argv[1] || '') === fileURLToPath(import.meta.url)) {
  for (const [rel, content] of Object.entries(generateDevicePresets())) {
    writeGenerated(join(root, rel), content)
    console.log(`wrote ${rel}`)
  }
}
