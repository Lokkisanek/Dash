/**
 * Device presets for the HA panel's live preview (www/devices.js).
 *
 * Phones and tablets take their CSS pixel size from Playwright's installed
 * device registry (`devices` in the playwright package): `screen` when it is
 * given (the whole display, what an installed PWA gets), else `viewport`.
 * Wall displays are typical panel resolutions, added by hand.
 * Safe-area insets are APPROXIMATIONS (typical values per device class), not
 * measured; the panel says so next to every preset.
 *
 *   node scripts/gen-device-presets.mjs     (npm run gen:devices)
 *
 * scripts/check-generated.mjs imports generateDevicePresets() and compares.
 */
