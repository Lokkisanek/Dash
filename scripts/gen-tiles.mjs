#!/usr/bin/env node
/**
 * Generates the tile registry for the guest app, the HA panel and the
 * integration from shared/tiles.json, so all three agree on device types,
 * styles and sizes.
 *
 *   node scripts/gen-tiles.mjs        (npm run gen:tiles)
 *
 * scripts/check-generated.mjs imports generateTiles() and compares the output
 * with the committed files.
 */
import { readFileSync } from 'node:fs'
import { fileURLToPath } from 'node:url'
import { dirname, join, resolve } from 'node:path'
import { writeGenerated } from './write-generated.mjs'

const root = join(dirname(fileURLToPath(import.meta.url)), '..')
const SOURCE = 'shared/tiles.json'
const SIZE_RE = /^[1-4]x[1-4]$/
const NAME_RE = /^[a-z][a-z0-9_]*$/

export const TILE_OUTPUTS = {
  app: 'src/lib/tileRegistry.generated.js',
  panel: 'custom_components/guest_ha_dashboard/www/tiles.js',
  integration: 'custom_components/guest_ha_dashboard/tile_registry.py',
}

/** Load and check shared/tiles.json; throws with a readable message. */
export function loadTiles(base = root) {
  const data = JSON.parse(readFileSync(join(base, SOURCE), 'utf8'))
  const errors = []
  const cols = data.gridCols
  if (!Number.isInteger(cols) || cols < 1) errors.push('gridCols must be a positive integer')
  const types = data.types || {}
  if (!Object.keys(types).length) errors.push('no types')
  for (const [name, t] of Object.entries(types)) {
    const where = `types.${name}`
    if (!NAME_RE.test(name)) errors.push(`${where}: bad type name`)
    if (typeof t.label !== 'string' || !t.label) errors.push(`${where}.label missing`)
    if (typeof t.icon !== 'string' || !t.icon) errors.push(`${where}.icon missing`)
    if (typeof t.needsEntity !== 'boolean') errors.push(`${where}.needsEntity must be true/false`)
    if (!Array.isArray(t.domains)) errors.push(`${where}.domains must be a list`)
    if (t.needsEntity && !t.domains?.length) errors.push(`${where}: needsEntity without domains`)
    const styles = Object.entries(t.styles || {})
    if (!styles.length) errors.push(`${where}.styles is empty`)
    for (const [style, sizes] of styles) {
      if (!NAME_RE.test(style)) errors.push(`${where}.styles.${style}: bad style name`)
      if (!Array.isArray(sizes) || !sizes.length) errors.push(`${where}.styles.${style}: no sizes`)
      for (const size of sizes || []) {
        if (!SIZE_RE.test(size)) errors.push(`${where}.styles.${style}: bad size ${size}`)
        else if (Number(size.split('x')[0]) > cols) errors.push(`${where}.styles.${style}: ${size} wider than the grid`)
      }
    }
    for (const [field, spec] of Object.entries(t.fields || {})) {
      if (spec?.type !== 'string' || !Number.isInteger(spec.max)) {
        errors.push(`${where}.fields.${field}: only {"type":"string","max":N} is supported`)
      }
    }
  }
  if (errors.length) throw new Error(`${SOURCE} is invalid:\n  ${errors.join('\n  ')}`)
  return { gridCols: cols, types }
}

/** Plain registry object written to the JS outputs. */
function registry(types) {
  return Object.fromEntries(
    Object.entries(types).map(([name, t]) => [
      name,
      {
        label: t.label,
        icon: t.icon,
        needsEntity: t.needsEntity,
        domains: t.domains,
        styles: t.styles,
        ...(t.fields ? { fields: t.fields } : {}),
      },
    ]),
  )
}

/** Python literal in the shape `ruff format` keeps (exploded, trailing commas). */
function py(value, indent = 0) {
  const pad = '    '.repeat(indent + 1)
  const end = '    '.repeat(indent)
  if (value === true) return 'True'
  if (value === false) return 'False'
  if (value === null) return 'None'
  if (typeof value === 'number') return String(value)
  if (typeof value === 'string') return JSON.stringify(value)
  if (Array.isArray(value)) {
    if (!value.length) return '[]'
    return `[\n${value.map((v) => `${pad}${py(v, indent + 1)},`).join('\n')}\n${end}]`
  }
  const entries = Object.entries(value)
  if (!entries.length) return '{}'
  return `{\n${entries.map(([k, v]) => `${pad}${JSON.stringify(k)}: ${py(v, indent + 1)},`).join('\n')}\n${end}}`
}

/** { relative path: file content } for every generated file. */
export function generateTiles(base = root) {
  const { gridCols, types } = loadTiles(base)
  const reg = registry(types)
  const json = JSON.stringify(reg, null, 2)
  const head = `Generated by scripts/gen-tiles.mjs from ${SOURCE}. Do not edit; run \`npm run gen:tiles\`.`

  const app =
    `/* ${head} */\n` +
    `export const GRID_COLS = ${gridCols}\n\n` +
    `export const TILE_TYPES = ${json}\n`

  const panel =
    `/* ${head} */\n` +
    `export const GRID_COLS = ${gridCols};\n\n` +
    `export const TILE_TYPES = ${json};\n`

  const python =
    `"""${head}"""\n\n` +
    `GRID_COLS = ${gridCols}\n\n` +
    `TILE_TYPES: dict[str, dict] = ${py(reg)}\n`

  return {
    [TILE_OUTPUTS.app]: app,
    [TILE_OUTPUTS.panel]: panel,
    [TILE_OUTPUTS.integration]: python,
  }
}

if (process.argv[1] && fileURLToPath(import.meta.url) === resolve(process.argv[1])) {
  const files = generateTiles()
  for (const [rel, content] of Object.entries(files)) writeGenerated(join(root, rel), content)
  console.log(`tiles: ${Object.keys(loadTiles().types).length} types → ${Object.keys(files).join(', ')}`)
}
