/**
 * Generates the icon sets shared by the guest PWA and the HA config panel
 * from lucide, so both always offer the same names.
 *
 *   node scripts/gen-icons.mjs
 */
import { readFileSync, writeFileSync } from 'node:fs'
import { fileURLToPath } from 'node:url'
import { dirname, join } from 'node:path'

const root = join(dirname(fileURLToPath(import.meta.url)), '..')
const lucideDir = join(root, 'node_modules/lucide-vue-next/dist/esm/icons')

/** Icons offered in the config icon picker. */
const PICKER_ICONS = [
  'Home', 'Sofa', 'BedDouble', 'Bed', 'Bath', 'ShowerHead', 'DoorOpen', 'DoorClosed',
  'Lamp', 'LampDesk', 'LampFloor', 'Lightbulb', 'Tv', 'Monitor', 'Speaker', 'Music',
  'Fan', 'AirVent', 'Flame', 'Thermometer', 'Snowflake', 'Sun', 'Moon', 'Sunrise',
  'Sunset', 'Coffee', 'CookingPot', 'Refrigerator', 'WashingMachine', 'Microwave', 'Utensils', 'Wine',
  'Power', 'Plug', 'Zap', 'Lock', 'Key', 'Shield', 'Camera', 'Car',
  'Warehouse', 'Trees', 'Flower2', 'Droplets', 'Waves', 'Router', 'Gamepad2', 'Baby',
  'Dog', 'Clapperboard', 'Blinds', 'Sparkles', 'Star', 'Heart', 'BookOpen', 'Dumbbell',
]

/** Extra UI icons used by the PWA itself (not offered in the picker). */
const UI_ICONS = ['Check', 'ChevronDown', 'ChevronUp', 'Copy', 'Minus', 'Plus', 'Square', 'Wifi', 'X']

/** Export name → icon file, resolving lucide aliases (e.g. Home → house.js). */
const exportFiles = new Map()
const indexSrc = readFileSync(join(lucideDir, '../lucide-vue-next.js'), 'utf8')
for (const m of indexSrc.matchAll(/export \{([^}]+)\} from '\.\/icons\/([^']+)'/g)) {
  for (const part of m[1].split(',')) {
    const alias = part.trim().split(/\s+as\s+/)[1]
    if (alias) exportFiles.set(alias, m[2])
  }
}

function iconNode(name) {
  const file = exportFiles.get(name)
  if (!file) throw new Error(`Unknown lucide icon: ${name}`)
  const src = readFileSync(join(lucideDir, file), 'utf8')
  const start = src.indexOf('[', src.indexOf('createLucideIcon('))
  const end = src.lastIndexOf(']);')
  return Function(`return ${src.slice(start, end + 1)}`)()
}

function toSvgInner(node) {
  return node
    .map(([tag, attrs]) => {
      const a = Object.entries(attrs)
        .filter(([k]) => k !== 'key')
        .map(([k, v]) => `${k}="${v}"`)
        .join(' ')
      return `<${tag} ${a}/>`
    })
    .join('')
}

const panelMap = Object.fromEntries(PICKER_ICONS.map((n) => [n, toSvgInner(iconNode(n))]))
writeFileSync(
  join(root, 'custom_components/guest_ha_dashboard/www/icons.js'),
  `/* Generated by scripts/gen-icons.mjs from lucide (ISC) — do not edit. */\n` +
    `export const ICONS = ${JSON.stringify(panelMap, null, 2)};\n`,
)

const all = [...new Set([...PICKER_ICONS, ...UI_ICONS])].sort()
writeFileSync(
  join(root, 'src/lib/icons.js'),
  `/* Generated by scripts/gen-icons.mjs — do not edit. Picker icons match the HA panel. */\n` +
    `import {\n${all.map((n) => `  ${n},`).join('\n')}\n} from 'lucide-vue-next'\n\n` +
    `export const icons = {\n${all.map((n) => `  ${n},`).join('\n')}\n}\n\n` +
    `export const PICKER_ICONS = ${JSON.stringify(PICKER_ICONS)}\n\n` +
    `export function resolveIcon(name, fallback = 'Sparkles') {\n` +
    `  return icons[name] || icons[fallback] || Sparkles\n}\n`,
)

console.log(`icons: ${PICKER_ICONS.length} picker, ${all.length} total`)
