/**
 * Generates the icon sets shared by the guest PWA and the HA config panel
 * from lucide (ISC) and scripts/icon-catalog.json, so both offer the same names.
 *
 *   node scripts/gen-icons.mjs      (npm run gen:icons)
 *
 * Outputs:
 *   src/lib/icons.js, src/lib/icons.extra.js           named lucide imports (tree-shaken) for the app;
 *                                                     the extra set is a lazy chunk
 *   custom_components/guest_ha_dashboard/www/icons.js  SVG markup of the base set, loaded with the panel
 *   custom_components/guest_ha_dashboard/www/icon-catalog.js
 *                                                     every catalog icon with categories and keywords,
 *                                                     imported by the panel only when the picker opens
 *
 * Every catalog name must exist in the installed lucide-vue-next; the script
 * stops and lists the ones that do not. scripts/check-generated.mjs imports
 * generateIcons() and compares its output with the committed files.
 */
import { readFileSync } from 'node:fs'
import { fileURLToPath } from 'node:url'
import { dirname, join, resolve } from 'node:path'
import { writeGenerated } from './write-generated.mjs'

const root = join(dirname(fileURLToPath(import.meta.url)), '..')
const lucideDir = join(root, 'node_modules/lucide-vue-next/dist/esm/icons')
const CATALOG = 'scripts/icon-catalog.json'

/**
 * The 56 icons the picker offered up to 2.1. Stored configs use these names, so
 * they must stay in the catalog; they also form the panel's base set (no lazy load).
 */
export const LEGACY_ICONS = [
  'Home', 'Sofa', 'BedDouble', 'Bed', 'Bath', 'ShowerHead', 'DoorOpen', 'DoorClosed',
  'Lamp', 'LampDesk', 'LampFloor', 'Lightbulb', 'Tv', 'Monitor', 'Speaker', 'Music',
  'Fan', 'AirVent', 'Flame', 'Thermometer', 'Snowflake', 'Sun', 'Moon', 'Sunrise',
  'Sunset', 'Coffee', 'CookingPot', 'Refrigerator', 'WashingMachine', 'Microwave', 'Utensils', 'Wine',
  'Power', 'Plug', 'Zap', 'Lock', 'Key', 'Shield', 'Camera', 'Car',
  'Warehouse', 'Trees', 'Flower2', 'Droplets', 'Waves', 'Router', 'Gamepad2', 'Baby',
  'Dog', 'Clapperboard', 'Blinds', 'Sparkles', 'Star', 'Heart', 'BookOpen', 'Dumbbell',
]

/** Extra UI icons used by the PWA itself (not offered in the picker). */
const UI_ICONS = ['Check', 'ChevronDown', 'ChevronUp', 'Copy', 'Minus', 'Plus', 'Square', 'Wifi', 'X']

const HEAD = 'Generated by scripts/gen-icons.mjs from lucide (ISC) and scripts/icon-catalog.json. Do not edit.'

/** Export name → icon file, resolving lucide aliases (e.g. Home → house.js). */
function lucideExports() {
  const files = new Map()
  const indexSrc = readFileSync(join(lucideDir, '../lucide-vue-next.js'), 'utf8')
  for (const m of indexSrc.matchAll(/export \{([^}]+)\} from '\.\/icons\/([^']+)'/g)) {
    for (const part of m[1].split(',')) {
      const alias = part.trim().split(/\s+as\s+/)[1]
      if (alias) files.set(alias, m[2])
    }
  }
  return files
}

function iconNode(files, name) {
  const src = readFileSync(join(lucideDir, files.get(name)), 'utf8')
  const start = src.indexOf('[', src.indexOf('createLucideIcon('))
  const end = src.lastIndexOf(']);')
  return Function(`return ${src.slice(start, end + 1)}`)()
}

function toSvgInner(node) {
  return node
    .map(([tag, attrs]) => {
      const a = Object.entries(attrs)
        .filter(([k]) => k !== 'key')
        .map(([k, v]) => `${k}="${v}"`)
        .join(' ')
      return `<${tag} ${a}/>`
    })
    .join('')
}

/** Read and check the catalog; throws listing every problem at once. */
export function loadIconCatalog(files = lucideExports()) {
  const data = JSON.parse(readFileSync(join(root, CATALOG), 'utf8'))
  const categories = data.categories || []
  const catIds = new Set(categories.map((c) => c.id))
  const icons = data.icons || []
  const problems = []
  const seen = new Set()
  for (const icon of icons) {
    if (seen.has(icon.name)) problems.push(`duplicate: ${icon.name}`)
    seen.add(icon.name)
    if (!files.has(icon.name)) problems.push(`not in the installed lucide-vue-next: ${icon.name}`)
    if (!catIds.has(icon.category)) problems.push(`${icon.name}: unknown category "${icon.category}"`)
    if (!icon.keywords?.cs?.length || !icon.keywords?.en?.length) problems.push(`${icon.name}: needs cs and en keywords`)
  }
  for (const name of LEGACY_ICONS) {
    if (!seen.has(name)) problems.push(`legacy icon removed from the catalog (stored configs use it): ${name}`)
  }
  for (const name of UI_ICONS) {
    if (!files.has(name)) problems.push(`UI icon not in lucide-vue-next: ${name}`)
  }
  if (problems.length) throw new Error(`${CATALOG}:\n  ${problems.join('\n  ')}`)
  return { categories, icons }
}

/** { relative path: content } of every generated icon file. */
export function generateIcons() {
  const files = lucideExports()
  const { categories, icons } = loadIconCatalog(files)
  const svg = (name) => toSvgInner(iconNode(files, name))

  const base = Object.fromEntries(LEGACY_ICONS.map((n) => [n, svg(n)]))
  const catalogList = icons.map((i) => ({ n: i.name, c: i.category, cs: i.keywords.cs, en: i.keywords.en }))
  const catalogSvg = Object.fromEntries(icons.map((i) => [i.name, svg(i.name)]))

  const picker = icons.map((i) => i.name)
  const baseApp = [...new Set([...LEGACY_ICONS, ...UI_ICONS])].sort()
  const extraApp = picker.filter((n) => !baseApp.includes(n)).sort()

  return {
    'custom_components/guest_ha_dashboard/www/icons.js':
      `/* ${HEAD} Base set, loaded with the panel. */\n` +
      `export const ICONS = ${JSON.stringify(base, null, 2)};\n`,
    'custom_components/guest_ha_dashboard/www/icon-catalog.js':
      `/* ${HEAD} Loaded by the panel when the icon picker opens. */\n` +
      `export const CATEGORIES = ${JSON.stringify(categories)};\n\n` +
      `/** n = lucide name, c = category, cs/en = search keywords */\n` +
      `export const ICON_LIST = [\n${catalogList.map((i) => `  ${JSON.stringify(i)},`).join('\n')}\n];\n\n` +
      `export const SVG = {\n${Object.entries(catalogSvg).map(([n, s]) => `  ${n}: ${JSON.stringify(s)},`).join('\n')}\n};\n`,
    'src/lib/icons.js': appIcons(picker, baseApp),
    'src/lib/icons.extra.js': extraIcons(extraApp),
  }
}

if (process.argv[1] && fileURLToPath(import.meta.url) === resolve(process.argv[1])) {
  try {
    const out = generateIcons()
    for (const [rel, content] of Object.entries(out)) writeGenerated(join(root, rel), content)
    const { icons, categories } = loadIconCatalog()
    console.log(`icons: ${icons.length} in ${categories.length} categories, base set ${LEGACY_ICONS.length}`)
  } catch (err) {
    console.error(err.message)
    process.exit(1)
  }
}

function list(names) {
  return names.map((n) => `  ${n},`).join(String.fromCharCode(10))
}

/** src/lib/icons.js: base set bundled with the app, the rest loaded as a separate chunk. */
function appIcons(picker, baseApp) {
  return [
    `/* ${HEAD} Picker icons match the HA panel. */`,
    `import { shallowReactive } from 'vue'`,
    `import {`,
    list(baseApp),
    `} from 'lucide-vue-next'`,
    ``,
    `/**`,
    ` * The base set (the icons offered up to 2.1 plus UI icons) is bundled with the app;`,
    ` * the rest of the catalog arrives in a separate chunk right after start-up.`,
    ` * Components call resolveIcon() in a template or computed, so they update when it lands.`,
    ` */`,
    `export const icons = shallowReactive({`,
    list(baseApp),
    `})`,
    ``,
    `export const PICKER_ICONS = ${JSON.stringify(picker)}`,
    ``,
    `export const LEGACY_ICONS = ${JSON.stringify(LEGACY_ICONS)}`,
    ``,
    `let loading = null`,
    `export function loadAllIcons() {`,
    `  loading ||= import('./icons.extra.js').then((m) => Object.assign(icons, m.EXTRA_ICONS))`,
    `  return loading`,
    `}`,
    ``,
    `if (typeof window !== 'undefined') loadAllIcons().catch((err) => console.warn('[dash] icons failed to load', err))`,
    ``,
    `export function resolveIcon(name, fallback = 'Sparkles') {`,
    `  return icons[name] || icons[fallback] || Sparkles`,
    `}`,
    ``,
  ].join(String.fromCharCode(10))
}

/** src/lib/icons.extra.js: every other catalog icon. */
function extraIcons(extraApp) {
  return [
    `/* ${HEAD} Loaded lazily by src/lib/icons.js. */`,
    `import {`,
    list(extraApp),
    `} from 'lucide-vue-next'`,
    ``,
    `export const EXTRA_ICONS = {`,
    list(extraApp),
    `}`,
    ``,
  ].join(String.fromCharCode(10))
}
