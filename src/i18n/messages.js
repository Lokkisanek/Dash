export function translateWeather(lang, condition) {
  const l = normalizeLang(lang)
  return messages[l]?.wx?.[condition] ?? messages.cs.wx[condition] ?? condition ?? ''
}

export function normalizeLang(value) {
  return value === 'en' ? 'en' : 'cs'
}

export function translate(lang, key) {
  const l = normalizeLang(lang)
  return messages[l]?.[key] ?? messages.cs[key] ?? key
}
